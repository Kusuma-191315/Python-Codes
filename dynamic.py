#For same variable in python we can hold different different types of data so this is the reason why python is called dynamically typed programming language
a = 10 #integer value
print(type(a))

a = "deep" #String value
print(type(a))

a = 3.14 #float  value
print(type(a))

a = True #boolen value
print(type(a))

#output will be <class 'int"> <class 'str'> <class 'float'> <class bool'>